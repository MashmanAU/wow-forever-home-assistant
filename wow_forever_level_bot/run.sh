export USE_CLASS_COLOURS="$(bashio::config 'use_class_colours')"
export SHOW_CLASS_ICONS="$(bashio::config 'show_class_icons')"
export SHOW_PROFESSION_ICONS="$(bashio::config 'show_profession_icons')"
